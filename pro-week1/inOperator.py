my_list = [1, 2, 3, 4, 5]

# Check if a value exists in the list using if statement
if 3 in my_list:
    print("Value 3 is in the list")
else:
    print("Value 3 is not in the list")

# Another example
if 6 in my_list:
    print("Value 6 is in the list")
else:
    print("Value 6 is not in the list")

my_dict = {'a': 1, 'b': 2, 'c': 3}

# Check if a key exists in the dictionary using if statement
if 'b' in my_dict:
    print("Key 'b' exists in the dictionary")
else:
    print("Key 'b' does not exist in the dictionary")

# Another example
if 'd' in my_dict:
    print("Key 'd' exists in the dictionary")
else:
    print("Key 'd' does not exist in the dictionary")

