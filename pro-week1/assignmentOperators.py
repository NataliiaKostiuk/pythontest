# Assignment (=)
x = 20
print("Assignment (x = 20):", x)  # Output: 20

# Addition Assignment (+=)
x += 5
print("Addition Assignment (x += 5):", x)  # Output: 25

# Subtraction Assignment (-=)
x -= 10
print("Subtraction Assignment (x -= 10):", x)  # Output: 15

# Multiplication Assignment (*=)
x *= 2
print("Multiplication Assignment (x *= 2):", x)  # Output: 30

# Division Assignment (/=)
x /= 3
print("Division Assignment (x /= 3):", x)  # Output: 10.0

# Floor Division Assignment (//=)
x //= 3
print("Floor Division Assignment (x //= 3):", x)  # Output: 3.0

# Modulus Assignment (%=)
x %= 2
print("Modulus Assignment (x %= 2):", x)  # Output: 1.0

# Exponentiation Assignment (**=)
x **= 3
print("Exponentiation Assignment (x **= 3):", x)  # Output: 1.0

# Assigning values using multiple variables
a = b = 10
print("Assigning values using multiple variables:", a, b)  # Output: 10 

