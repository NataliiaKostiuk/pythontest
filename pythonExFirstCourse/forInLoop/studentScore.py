# Список с баллами учеников
student_scores = [70, 45, 85, 30, 65]

# Перебор каждого балла и проверка с помощью тернарного оператора
for score in student_scores:
    result = "Pass" if score >= 60 else "Fail"
    print(f"Score: {score} - {result}")


age = int(input("Введите ваш возраст: "))
citizenship = input("Введите ваш статус гражданства (гражданин/негражданин): ").lower()

# Проверяем право голосовать
if age >= 18 and citizenship == "гражданин":
    print("Вы имеете право голосовать.")
else:
    print("Вы не имеете права голосовать.")

# Проверяем право водить автомобиль
if age >= 16 and citizenship == "гражданин":
    print("Вы имеете право водить автомобиль.")
else:
    print("Вы не имеете права водить автомобиль.")


# Составляем список имен учащихся
students = ["Алексей", "Виктория", "Иван", "Мария", "Дмитрий", "Екатерина", "Анна", "Сергей", "Ольга", "Максим"]

# 1. Печатаем исходный список имен учащихся
print("Исходный список студентов:", students)

# 2. Получаем и печатаем первые 5 имен
first_five_students = students[:5]
print("Первые 5 студентов:", first_five_students)

# 3. Получаем и печатаем последние 3 имени
last_three_students = students[-3:]
print("Последние 3 студента:", last_three_students)

# 4. Получаем размер списка и печатаем его
list_size = len(students)
print("Размер списка студентов:", list_size)

# 5. Добавляем новое имя "Кейт" в конец списка
students.append("Кейт")
print("Список после добавления 'Кейт':", students)

# 6. Вставляем имя "Лиам" в индекс 3
students.insert(3, "Лиам")
print("Список после вставки 'Лиам' на индекс 3:", students)

# 7. Перебираем и печатаем имя каждого учащегося
print("Список студентов по именам:")
for student in students:
    print(student)